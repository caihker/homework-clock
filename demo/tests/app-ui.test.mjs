import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const html = await readFile(new URL('../dist/index.html', import.meta.url), 'utf8');
const app = await readFile(new URL('../dist/app-controller.mjs', import.meta.url), 'utf8');
const timelineView = await readFile(new URL('../dist/timeline-view.mjs', import.meta.url), 'utf8');

test('the home page discloses foreground-only reminders and no app limits', () => {
  assert.match(html, /仅前台提醒 · 不限制其他 App/);
  assert.match(html, /本版本不提供应用限制/);
  assert.match(html, /提醒仅在应用打开时生效，本版本不限制其他 App/);
});

test('closing settings asks before discarding an unsaved draft', () => {
  assert.match(app, /function requestSettingsClose\(\)/);
  assert.match(app, /hasSettingsDraft\(state\.settings,settingsDraft\(\)\)/);
  assert.match(app, /dialog\?\.id==='settings-dialog'\)requestSettingsClose\(\)/);
  assert.match(app, /settings-dialog'\)\.addEventListener\('cancel'/);
});

test('the day timeline offers free-text notes without a time window', () => {
  assert.match(html, /id="notes-list"/);
  assert.match(html, /id="add-note"/);
  assert.match(html, /id="note-dialog"/);
  assert.match(html, /maxlength="300"/);
  assert.match(timelineView, /function renderNotes\(\)/);
  assert.match(app, /state\.notes=\[\.\.\.\(state\.notes\|\|\[\]\)/);
});

test('reusable plans and calendar export are exposed without a server', () => {
  assert.match(html, /id="custom-template-chips"/);
  assert.match(html, /id="save-template"/);
  assert.match(html, /id="template-manager"/);
  assert.match(html, /id="export-calendar"/);
  assert.match(app, /function saveTemplate\(\)/);
  assert.match(app, /buildCalendar\(tasks/);
});

test('a new day opens on today while demo mode keeps its chosen date', () => {
  assert.match(app, /dailyDate\(\{ selectedDate: state\.selectedDate/);
  assert.match(app, /function syncToday\(\)/);
  assert.match(app, /state\.selectedDate<dateKey\(new Date\(\)\)/);
});

test('day notes live in the current-arrangement card instead of the timeline', () => {
  const current = html.indexOf('class="current-card"');
  const notes = html.indexOf('class="notes-panel"');
  const schedule = html.indexOf('class="schedule-panel"');
  assert.ok(current >= 0 && schedule > current);
  assert.ok(notes > current && notes < schedule, 'notes must be inside the left current card');
});

test('turtle sayings sit under notes inside the current card and can refresh', () => {
  const notes = html.indexOf('class="notes-panel"');
  const words = html.indexOf('class="turtle-words"');
  const pet = html.indexOf('class="pet-card"');
  assert.ok(notes > 0 && words > notes && pet > words, 'notes -> turtle words -> companion order');
  assert.match(html, /id="turtle-words-text"/);
  assert.match(html, /id="next-turtle-word"/);
  assert.match(app, /function renderTurtleWords\(\)/);
  assert.match(app, /pickTurtleWord\(currentTurtleWord\)/);
  assert.match(app, /\$\('#next-turtle-word'\)\.onclick=renderTurtleWords/);
});

test('audit fixes guard note drafts, keep edit dates and preserve active timers', () => {
  assert.match(app, /'#note-dialog'\].some/);
  assert.match(app, /let taskEditingDate = null;/);
  assert.match(app, /let noteEditingDate = null;/);
  assert.match(app, /date:old\?\.date\|\|taskEditingDate\|\|state\.selectedDate/);
  assert.match(app, /当前还有计时进行中，请先结束或暂停计时，再恢复备份/);
  assert.match(app, /normalized\.droppedNotes\+normalized\.droppedTemplates/);
  assert.match(app, /taskEnd\(t\)<=now\(\)\.getTime\(\)\)\{openFinish\(t\);return;\}/);
});

