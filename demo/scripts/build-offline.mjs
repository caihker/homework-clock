import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const demo = dirname(dirname(fileURLToPath(import.meta.url)));
const dist = join(demo, 'dist');
const excluded = new Set(['sw.js']);
// These retained design iterations are not used by the current runtime. Keep
// their source files on disk, but do not make a new iPad download them to start.
const excludedDirectories = new Set([
  'assets/category-3d-v2',
  'assets/category-flat-v1',
  'assets/motion',
]);
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const localPath = (root, path) => relative(root, path).split('\\').join('/');

async function walk(directory, root) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name.startsWith('.')) continue;
    const path = join(directory, entry.name);
    const key = localPath(root, path);
    if (entry.isDirectory() && !excludedDirectories.has(key)) files.push(...await walk(path, root));
    else if (entry.isFile() && !excluded.has(key)) files.push(path);
  }
  return files;
}

/** Include all current fonts, animations and voice clips, even before use. */
export async function collectOfflineAssets(directory = dist) {
  const files = (await walk(directory, directory)).sort();
  return Promise.all(files.map(async path => {
    const key = localPath(directory, path);
    const content = await readFile(path);
    const asset = { url: './' + key, sha256: sha256(content), bytes: content.length };
    // Private hosting may wrap the network HTML response. Cache the canonical
    // source from this same versioned build instead, still checking its hash in SW.
    // The version below covers the inline bytes as well as the declared digest.
    if (key === 'index.html') asset.inline = content.toString('utf8');
    return asset;
  }));
}

async function main() {
  const template = await readFile(join(demo, 'scripts/service-worker.template.js'), 'utf8');
  const assets = await collectOfflineAssets();
  const version = sha256(JSON.stringify(assets) + template).slice(0, 20);
  const worker = `/* Generated by scripts/build-offline.mjs. Run again after changing dist. */\nconst BUILD = ${JSON.stringify({version, assets}, null, 2)};\n${template}`;
  const destination = join(dist, 'sw.js');
  if (process.argv.includes('--check')) {
    if (await readFile(destination, 'utf8').catch(() => '') !== worker) {
      throw new Error('离线资源清单已过期，请先运行 node scripts/build-offline.mjs');
    }
    process.stdout.write(`Offline manifest is current: ${assets.length} resources, ${version}\n`);
  } else {
    await writeFile(destination, worker);
    process.stdout.write(`Offline bundle: ${assets.length} resources, ${(assets.reduce((sum, asset) => sum + asset.bytes, 0) / 1024 / 1024).toFixed(1)} MB, ${version}\n`);
  }
}

// Tests import the collector without regenerating sw.js as a side effect.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
