"""Convert the original OFL fonts to self-hosted WOFF2; keep all glyphs.

Usage: python prepare-fonts.py ROUND_ZIP COMIC_TTF COMIC_OFL
Requires fonttools[woff]. Family names are changed to avoid reserved names.
"""
from hashlib import sha256
from io import BytesIO
from copy import deepcopy
import json
from pathlib import Path
import sys
from zipfile import ZipFile

from fontTools.ttLib import TTFont
from fontTools import subset

ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / "dist/assets/fonts"
UI_TEXT = "一二三四五六七日年月星期时分秒"
for source in ["index.html", "app.mjs", "core.mjs", "time-picker.mjs", "voice-pack.mjs"]:
    UI_TEXT += (ROOT / "dist" / source).read_text()
CORE_CHARACTERS = set(map(ord, UI_TEXT)) | set(range(32, 127))
FACES = []


def unicode_ranges(points):
    ranges = []
    for value in sorted(points):
        if ranges and value == ranges[-1][1] + 1:
            ranges[-1][1] = value
        else:
            ranges.append([value, value])
    return ",".join(f"U+{a:X}" if a == b else f"U+{a:X}-{b:X}" for a, b in ranges)


def convert(data, family, style, filename):
    font = TTFont(BytesIO(data))
    names = {1: family, 2: style, 3: f"{family.replace(' ', '')}-{style}-1.0",
             4: f"{family} {style}", 6: f"{family.replace(' ', '')}-{style}",
             16: family, 17: style}
    # Preserve the source's copyright, license, authorship and version records.
    font["name"].names = [r for r in font["name"].names if r.nameID not in names]
    for name_id, value in names.items():
        font["name"].setName(value, name_id, 3, 1, 0x409)
        font["name"].setName(value, name_id, 1, 0, 0)
    font.flavor = "woff2"
    destination = DESTINATION / filename
    font.save(destination)
    cmap = font.getBestCmap()
    core = deepcopy(font)
    options = subset.Options()
    options.layout_features = ["*"]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=CORE_CHARACTERS)
    subsetter.subset(core)
    core_filename = filename.replace(".woff2", ".core.woff2")
    core.save(DESTINATION / core_filename)
    core_points = set(core.getBestCmap())
    remaining_points = set(cmap) - core_points
    weight = 700 if style == "Bold" else 400
    for file, points in [(filename, remaining_points), (core_filename, core_points)]:
        FACES.append(f'@font-face{{font-family:"{family}";src:url("./assets/fonts/{file}") format("woff2");font-style:normal;font-weight:{weight};font-display:swap;unicode-range:{unicode_ranges(points)};}}')
    digits = {str(i): font["hmtx"].metrics[cmap[ord(str(i))]][0] for i in range(10)}
    return {"family": family, "style": style, "bytes": destination.stat().st_size,
            "source_sha256": sha256(data).hexdigest(), "characters": len(cmap),
            "core_file": core_filename, "core_bytes": (DESTINATION / core_filename).stat().st_size,
            "core_characters": len(core_points),
            "digit_advances": digits}


def main():
    round_archive, comic_file, comic_license = map(Path, sys.argv[1:])
    DESTINATION.mkdir(parents=True, exist_ok=True)
    metadata = {"round_source": "https://github.com/Warren2060/ChillRound/releases/tag/v3.200",
                "comic_source": "https://github.com/google/fonts/tree/main/ofl/zcoolkuaile",
                "license": "OFL-1.1", "conversion": "WOFF2, renamed family, UI subset plus complete fallback", "fonts": {}}
    with ZipFile(round_archive) as archive:
        for style in ["Regular", "Bold"]:
            entry = f"ChillRoundF_v3.200/ChillRoundF{style}.ttf"
            filename = f"homework-round-{style.lower()}.woff2"
            metadata["fonts"][filename] = convert(archive.read(entry), "Homework Round", style, filename)
        (DESTINATION / "OFL-ChillRound.txt").write_bytes(archive.read("ChillRoundF_v3.200/LICENSE.txt"))
    filename = "homework-comic.woff2"
    metadata["fonts"][filename] = convert(comic_file.read_bytes(), "Homework Comic", "Regular", filename)
    (DESTINATION / "OFL-ZCOOLKuaiLe.txt").write_bytes(comic_license.read_bytes())
    (ROOT / "dist/font-faces.css").write_text("/* Generated by scripts/prepare-fonts.py; disjoint ranges load only required glyphs. */\n" + "\n".join(FACES) + "\n")
    (DESTINATION / "metadata.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps(metadata["fonts"], ensure_ascii=False))


if __name__ == "__main__":
    main()
